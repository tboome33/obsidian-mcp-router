/**
 * A workspace bound to `work` (primary) with `writable-ref` / `locked-ref` /
 * `soft-ref` as secondaries — the three write tiers plus the primary, all
 * pointed at the SAME fake vault server (vault identity is the router's own
 * bookkeeping; the underlying store does not need to differ per name for
 * these tests, which only ask "did a write reach the server at all").
 */
function writeConfig(port, { vaultReach } = {}) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'also-tier-e2e-'));
  tmpDirs.push(dir);
  const configPath = path.join(dir, 'config.json');
  const baseUrl = `http://127.0.0.1:${port}`;
  const remote = (name) => ({ name, baseUrl, apiKey: API_KEY, timeoutMs: 5000 });
  const key = canonicalWorkspaceKey(dir);
  fs.writeFileSync(configPath, JSON.stringify({
    portRegistry: {},
    vaultNames: {},
    remoteVaults: [
      remote('work'),
      remote('writable-ref'),
      remote('locked-ref'),
      remote('soft-ref'),
    ],
    defaultVault: 'work',
    alsoWritable: ['writable-ref'],
    alsoLocked: ['locked-ref'],
    ...(vaultReach ? { vaultReach: 'declared', openVaults: [] } : {}),
    workspaceBindings: {
      [key]: {
        vault: 'work',
        also: ['writable-ref', 'locked-ref', 'soft-ref'],
        locked: false,
        confirmedAt: '2026-09-05',
        confirmedVia: 'test',
      },
    },
  }, null, 2), 'utf8');
  return { dir, configPath };
}

function startRouter({ configPath, cwd, env = {} }) {
  const child = spawn(process.execPath, [BIN, '--config', configPath], {
    cwd,
    env: homeSafeEnv(cwd, {
      OBSIDIAN_ROUTER_NO_WATCH: '1',
      MD_ALLOWED_PATHS: cwd,
      OBSIDIAN_ROUTER_LOCKED: '',
      OBSIDIAN_ROUTER_VIEW_AGENT_URL: '',
      OBSIDIAN_ROUTER_USER_ID: '',
      ...env,
    }),
    stdio: ['pipe', 'pipe', 'pipe'],
  });
  let stdout = '';
  let stderr = '';
  const waiters = new Map();
  child.stdout.setEncoding('utf8');
  child.stderr.setEncoding('utf8');
  child.stderr.on('data', (c) => { stderr += c; });
  child.stdout.on('data', (chunk) => {
    stdout += chunk;
    let nl;
    while ((nl = stdout.indexOf('\n')) !== -1) {
      const raw = stdout.slice(0, nl).trim();
      stdout = stdout.slice(nl + 1);
      if (!raw) continue;
      let msg;
      try { msg = JSON.parse(raw); } catch { continue; }
      const w = waiters.get(msg.id);
      if (w) { waiters.delete(msg.id); w(msg); }
    }
  });
  const send = (msg) => child.stdin.write(`${JSON.stringify(msg)}\n`);
  const call = (id, method, params) => new Promise((resolve, reject) => {
    const timer = setTimeout(
      () => reject(new Error(`timed out waiting for ${method}\n--- router stderr ---\n${stderr}`)),
      20000,
    );
    waiters.set(id, (m) => { clearTimeout(timer); resolve(m); });
    send({ jsonrpc: '2.0', id, method, params });
  });
  return { child, call, send, stderrText: () => stderr, kill: () => child.kill() };
}

async function handshake(rt) {
  await rt.call(1, 'initialize', {
    protocolVersion: '2024-11-05',
    capabilities: {},
    clientInfo: { name: 'also-tier-e2e', version: '0' },
  });
  rt.send({ jsonrpc: '2.0', method: 'notifications/initialized' });
}

/**
 * EVERY method that mutates the vault. Round 3 of the review caught the
 * earlier assertions filtering on PUT/DELETE only — while the audit line is
 * appended with POST. A "no write landed" assertion that ignores POST passes
 * whether or not the audit middleware fired: blind, not green.
 */
const MUTATING = new Set(['PUT', 'POST', 'PATCH', 'DELETE']);
const isMutation = (r) => MUTATING.has(r.method);

/** The write-related PUTs a `write_file` call would have made (excludes conformance's own index/projection writes). */
function contentPuts(vault, relPath) {
  return vault.seen.filter((r) => r.method === 'PUT' && r.url === `/vault/${relPath}`);
}

async function waitForIndexWrite(vault, { timeoutMs = 8000 } = {}) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (vault.seen.some((r) => r.method === 'PUT' && r.url === `/vault/${SEARCH_INDEX_PATH}`)) return true;
    await new Promise((r) => setTimeout(r, 50));
  }
  return false;
}

