/** Same loopback stand-in `vault-conformance-e2e.test.mjs` uses — see there for the request-record shape. */
async function startFakeVault(files) {
  const store = new Map(Object.entries(files));
  const seen = [];
  const server = http.createServer((req, res) => {
    let body = '';
    req.setEncoding('utf8');
    req.on('data', (c) => { body += c; });
    req.on('end', () => {
      const url = decodeURIComponent(req.url);
      seen.push({ method: req.method, url, body });
      if (url === '/') {
        res.writeHead(200, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ status: 'OK' }));
        return;
      }
      const rel = url.replace(/^\/vault\//, '');
      if (req.method === 'PUT') {
        store.set(rel, body);
        res.writeHead(204).end();
        return;
      }
      if (req.method === 'DELETE') {
        store.delete(rel);
        res.writeHead(204).end();
        return;
      }
      if (rel.endsWith('/') || rel === '') {
        const prefix = rel;
        const names = new Set();
        for (const p of store.keys()) {
          if (!p.startsWith(prefix)) continue;
          const rest = p.slice(prefix.length);
          const slash = rest.indexOf('/');
          names.add(slash === -1 ? rest : `${rest.slice(0, slash)}/`);
        }
        if (names.size === 0) { res.writeHead(404).end('not found'); return; }
        res.writeHead(200, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ files: [...names].sort() }));
        return;
      }
      if (!store.has(rel)) { res.writeHead(404).end('not found'); return; }
      res.writeHead(200, { 'Content-Type': 'text/markdown' });
      res.end(store.get(rel));
    });
  });
  await new Promise((r) => server.listen(0, '127.0.0.1', r));
  return {
    seen,
    store,
    port: server.address().port,
    close: () => new Promise((r) => server.close(r)),
  };
}

