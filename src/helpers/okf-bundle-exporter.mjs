// Embeds first (![[...]]), then plain wikilinks. Target may carry
// `#heading`, `#^block-id`, and `|alias` decorations.
const EMBED_RE = /!\[\[([^\]]+)\]\]/g;
const WIKILINK_RE = /\[\[([^\]]+)\]\]/g;

const ASSET_EXT_RE = /\.(png|jpe?g|gif|svg|webp|bmp|pdf|mp3|mp4|wav|ogg|mov|webm)$/i;

function splitWikiTarget(raw) {
  // `path/to/Page#Heading|Alias` → { target, anchor, alias }
  const pipeIdx = raw.indexOf('|');
  const alias = pipeIdx >= 0 ? raw.slice(pipeIdx + 1).trim() : null;
  const noAlias = pipeIdx >= 0 ? raw.slice(0, pipeIdx) : raw;
  const hashIdx = noAlias.indexOf('#');
  const anchor = hashIdx >= 0 ? noAlias.slice(hashIdx + 1).trim() : null;
  const target = (hashIdx >= 0 ? noAlias.slice(0, hashIdx) : noAlias).trim();
  return { target, anchor, alias };
}

/**
 * Build a resolver that maps a wikilink (or markdown-link) target string to
 * the NEW bundle-relative path of the page it designates.
 *
 * Resolution order (mirrors Obsidian's basename resolution):
 *   1. exact vault path (with or without `wiki/` prefix, with or without `.md`)
 *   2. basename, case-sensitive
 *   3. basename, case-insensitive
 *
 * When step 2 or 3 matches MULTIPLE pages (two source pages share a
 * basename across folders — an ambiguity Obsidian itself has, since a bare
 * `[[Foo]]` is basename-resolved there too), this resolver breaks the tie
 * by preferring a candidate that lives in the SAME bundle folder as the
 * citing page, falling back to the alphabetically-first candidate. The
 * choice is never silent — every ambiguous resolution is pushed to
 * `report.ambiguousLinks` so the export report surfaces it.
 *
 * @param {Array<{ path: string, newPath: string }>} mappings
 * @param {{ ambiguousLinks: string[] }} report Mutated on ambiguous matches
 * @returns {(target: string, fromNewPath: string) => string | null}
 *   New path, or null if not exported
 */
function makeTargetResolver(mappings, report) {
  const byVaultPath = new Map();
  const byBasename = new Map();
  const byBasenameLower = new Map();
  for (const m of mappings) {
    const noExt = m.path.replace(/\.md$/i, '');
    byVaultPath.set(noExt, m.newPath);
    byVaultPath.set(noExt.replace(/^wiki\//, ''), m.newPath);
    const basename = noExt.split('/').pop();
    if (!byBasename.has(basename)) byBasename.set(basename, []);
    byBasename.get(basename).push(m);
    const lower = basename.toLowerCase();
    if (!byBasenameLower.has(lower)) byBasenameLower.set(lower, []);
    byBasenameLower.get(lower).push(m);
  }

  // Tie-break priority: (1) a candidate matching the target's basename in
  // the EXACT case it was written, BUT ONLY when exactly one candidate
  // does — if ALL candidates equally match the exact case (a pure
  // same-basename-different-folder collision, no case ambiguity at play),
  // this tier is a no-op and must NOT short-circuit the more meaningful
  // (2) same-bundle-folder-as-citing-page tier below it. (3)
  // alphabetically-first. Every ambiguous resolution (2+ distinct
  // candidates) is reported regardless of which tier resolved it — an
  // exact-case match existing does NOT mean a case-differing twin
  // elsewhere is not worth flagging to the user.
  const pickCandidate = (candidates, fromNewPath, rawTarget, exactBasename) => {
    const exactCaseMatches = candidates.filter(
      (c) => c.path.replace(/\.md$/i, '').split('/').pop() === exactBasename,
    );
    const exactCase = exactCaseMatches.length === 1 ? exactCaseMatches[0] : null;
    const fromDir = fromNewPath.split('/').slice(0, -1).join('/');
    const sameDir = candidates.find(
      (c) => c.newPath.split('/').slice(0, -1).join('/') === fromDir,
    );
    const sorted = candidates.slice().sort((a, b) => a.newPath.localeCompare(b.newPath));
    const chosen = exactCase ?? sameDir ?? sorted[0];
    const reason = exactCase
      ? ' (exact-case preference)'
      : sameDir
        ? ' (same-folder preference)'
        : ' (first match, alphabetical — ambiguous)';
    report.ambiguousLinks.push(
      `${fromNewPath}: [[${rawTarget}]] matches ${candidates.length} pages (${sorted
        .map((c) => c.newPath)
        .join(', ')}) — resolved to ${chosen.newPath}${reason}`,
    );
    return chosen.newPath;
  };

  const resolve = (target, fromNewPath) => {
    const clean = target.replace(/\.md$/i, '');
    const exact = byVaultPath.get(clean);
    if (exact) return exact;
    const basename = clean.split('/').pop();
    // Union exact-case and case-insensitive candidate pools BEFORE deciding
    // whether the resolution is ambiguous. Checking exact-case alone and
    // stopping there (the original design) meant a single exact-case match
    // short-circuited even when a case-differing twin existed elsewhere
    // (e.g. `a/Foo.md` + `b/foo.md`, both realistically coexistable on a
    // case-preserving-but-insensitive filesystem across two different
    // folders) — that ambiguity went completely unreported.
    const exactCandidates = byBasename.get(basename) ?? [];
    const lowerCandidates = byBasenameLower.get(basename.toLowerCase()) ?? [];
    const seenPaths = new Set();
    const allCandidates = [];
    for (const c of [...exactCandidates, ...lowerCandidates]) {
      if (seenPaths.has(c.newPath)) continue;
      seenPaths.add(c.newPath);
      allCandidates.push(c);
    }
    if (allCandidates.length === 0) return null;
    if (allCandidates.length === 1) return allCandidates[0].newPath;
    return pickCandidate(allCandidates, fromNewPath, target, basename);
  };

  // Exact-vault-path-only resolution, no basename fallback, no ambiguity
  // reporting. Used for the FIRST (file-relative-join) attempt on a
  // standard markdown link: a joined path that fails this exact lookup
  // must be treated as genuinely not-found (dangling) by that attempt,
  // never silently reinterpreted as "well, ITS basename happens to match
  // some unrelated page elsewhere" — that basename-fallback behavior is
  // only appropriate for the caller's SECOND attempt, on the raw
  // as-authored target (see rewriteWikilinks' convertMarkdownLink).
  resolve.exact = (target) => byVaultPath.get(target.replace(/\.md$/i, '')) ?? null;

  return resolve;
}

// Standard markdown link/image to a `.md` target, with an optional
// `#anchor`. Captures the `!`-or-not label bracket verbatim so image syntax
// is preserved; only the path inside `(...)` is ever rewritten.
const MARKDOWN_MD_LINK_RE = /(!?\[[^\]]*\])\(([^()\s]+\.md)((?:#[^)\s]*)?)\)/g;

// Fenced code blocks (``` or ~~~, opening fence to the next occurrence of
// the same fence) and single-backtick inline code spans. Link-looking
// syntax inside either is illustrative example text (e.g. a wiki page
// documenting markdown-link or wikilink syntax itself), not a real link —
// none of the three rewriting passes below should ever touch it. Pragmatic
// approximation, not a full CommonMark tokenizer (doesn't match backtick-run
// length for nested inline code containing a literal backtick), but covers
// the vault content this router itself produces and consumes.
const CODE_SEGMENT_RE = /(```[\s\S]*?```|~~~[\s\S]*?~~~|`[^`\n]*`)/g;

/**
 * Split `body` on code segments (see `CODE_SEGMENT_RE`) and apply `rewrite`
 * only to the non-code segments, leaving fenced/inline code byte-for-byte
 * untouched.
 * @param {string} body
 * @param {(segment: string) => string} rewrite
 * @returns {string}
 */
function rewriteOutsideCode(body, rewrite) {
  return body
    .split(CODE_SEGMENT_RE)
    .map((segment, i) => (i % 2 === 0 ? rewrite(segment) : segment))
    .join('');
}

/**
 * Rewrite every `[[wikilink]]`, `![[embed]]`, AND pre-existing standard
 * markdown link/image pointing at a `.md` file in a page body into relative
 * markdown links between the bundle's slugified paths.
 *
 * Policies (all reported, never silent):
 *   - heading/block anchors are dropped (no OKF equivalent) → `anchorsDropped`
 *   - a same-document reference (`[[#Heading]]`, `[[^block-id]]` — empty
 *     target) has no OKF equivalent (no "current document" concept) and is
 *     demoted to plain text rather than guessing a nonexistent file →
 *     `anchorsDropped`
 *   - links to pages outside the export set become dangling links to the
 *     slugified guess of where the page WOULD live → `dangling`
 *   - embeds of markdown pages are demoted to plain links; embeds of assets
 *     become standard image links (assets are not exported) → `embeds`
 *   - existing markdown links whose target resolves to an exported page are
 *     repointed at its new slugified path (a source page can legally mix
 *     wikilinks and standard markdown links) → silent when already correct,
 *     otherwise folded into the same rewrite as wikilinks. Unlike
 *     wikilinks (vault-root/basename-relative, Obsidian's own model),
 *     standard markdown links are CommonMark file-relative — when
 *     `fromVaultPath` is provided, the raw target is joined against the
 *     citing page's own original directory FIRST (an unambiguous exact
 *     match) before ever falling back to basename matching, so an explicit
 *     `../refs/Other.md` can't be silently redirected to an unrelated
 *     same-named page in a different folder by the ambiguity tie-break
 *   - fenced code blocks and inline code spans are NEVER rewritten (see
 *     `rewriteOutsideCode`) — link-looking syntax there is example text
 *
 * Resolution of an ambiguous bare target (two exported pages share a
 * basename) is handled by `resolve` itself → `report.ambiguousLinks`.
 *
 * @param {string} body Page body (frontmatter already removed)
 * @param {string} fromNewPath Bundle-relative path of the page being rewritten
 * @param {(target: string, fromNewPath: string) => string | null} resolve Target resolver
 * @param {{ anchorsDropped: string[], dangling: string[], embeds: string[], ambiguousLinks: string[] }} report
 * @param {string} [fromVaultPath] Original vault-relative path of the page
 *   being rewritten (e.g. `wiki/concepts/Foo.md`) — enables correct
 *   file-relative resolution of standard markdown links. Omit only in
 *   isolated unit tests; production callers always have this.
 * @returns {string} Body with all Obsidian + markdown link syntax converted
 */
export function rewriteWikilinks(body, fromNewPath, resolve, report, fromVaultPath) {
  const fromVaultDir = fromVaultPath
    ? fromVaultPath.split('/').slice(0, -1).join('/')
    : null;
  const convertTarget = (raw, { isEmbed }) => {
    const { target, anchor, alias } = splitWikiTarget(raw);
    if (!target) {
      // Same-document reference — OKF has no notion of "the current
      // document" as a link target; a link to a synthesized dangling file
      // would be actively wrong, not just imprecise. Demote to plain text.
      const selfLabel = alias || anchor || raw;
      report.anchorsDropped.push(
        `${fromNewPath}: [[${raw}]] (self-document reference, link dropped)`,
      );
      return selfLabel;
    }
    if (anchor) report.anchorsDropped.push(`${fromNewPath}: [[${raw}]]`);
    const label = alias || target.split('/').pop().replace(/\.md$/i, '');
    if (isEmbed && ASSET_EXT_RE.test(target)) {
      // Asset embed — keep image syntax, point at the slugified basename
      // (assets are not exported; the link is knowingly dangling).
      const assetName = target.split('/').pop();
      const ext = assetName.match(ASSET_EXT_RE)[0];
      const stem = assetName.slice(0, -ext.length);
      report.embeds.push(`${fromNewPath}: ![[${raw}]] (asset, not exported)`);
      return `![${label}](${slugifyOkfSegment(stem)}${ext.toLowerCase()})`;
    }
    const resolved = resolve(target, fromNewPath);
    let linkPath;
    if (resolved) {
      linkPath = relativeLink(fromNewPath, resolved);
    } else {
      // Dangling — legal per §5.3 ("not-yet-written knowledge"). Point at the
      // slugified path the page would have if it were exported.
      const guess = slugifyOkfPath(target.includes('/') ? target : `${target}.md`);
      linkPath = relativeLink(fromNewPath, guess);
      report.dangling.push(`${fromNewPath}: [[${raw}]] → ${guess}`);
    }
    if (isEmbed && !ASSET_EXT_RE.test(target)) {
      report.embeds.push(`${fromNewPath}: ![[${raw}]] (demoted to plain link)`);
    }
    return `[${label}](${linkPath})`;
  };

  const convertMarkdownLink = (full, labelPart, rawPath, anchorPart) => {
    // Absolute URLs (http(s):, mailto:, protocol-relative //) are never
    // vault pages — leave untouched. A relative path is anything else.
    if (/^[a-z][a-z0-9+.-]*:/i.test(rawPath) || rawPath.startsWith('//')) return full;
    let decoded = rawPath;
    try {
      decoded = decodeURIComponent(rawPath);
    } catch {
      // Malformed percent-encoding — resolve against the raw text instead
      // of throwing; worst case the lookup simply misses (link untouched).
    }
    const resolveExact = (p) => (typeof resolve.exact === 'function' ? resolve.exact(p) : null);
    let resolved = null;
    if (decoded.includes('/')) {
      // Path-shaped target (contains a `/`, e.g. `../refs/Other.md` or
      // `sub/Other.md`) — the author gave us STRUCTURAL information that
      // must be respected. Try an EXACT vault-path match only: join
      // against the citing page's own original folder first, then the raw
      // text as-is (covers an already vault-relative path). NEVER fall
      // back to basename matching for a path-shaped target — that would
      // let an explicit but broken relative link (e.g.
      // `../nonexistent/Target.md`) get silently "accidentally" repointed
      // at any unrelated page elsewhere in the vault that happens to share
      // the same basename, which is worse than leaving it dangling.
      if (fromVaultDir !== null) {
        resolved = resolveExact(joinVaultRelativePath(fromVaultDir, decoded));
      }
      if (!resolved) resolved = resolveExact(decoded);
    } else {
      // Bare filename, no path information at all — basename-style
      // resolution (with ambiguity detection/reporting) is the only
      // option, matching how Obsidian itself resolves a bare wikilink.
      resolved = resolve(decoded, fromNewPath);
    }
    if (!resolved) return full; // not one of our exported pages — leave as-authored
    if (anchorPart) {
      report.anchorsDropped.push(
        `${fromNewPath}: ${labelPart}(${rawPath}${anchorPart}) [markdown link anchor]`,
      );
    }
    const newRelative = relativeLink(fromNewPath, resolved);
    // Truly a no-op only when BOTH the path is already correct AND there's
    // no anchor to strip — a matching path with a trailing #anchor must
    // still be rewritten to actually drop that anchor.
    if (newRelative === rawPath && !anchorPart) return full;
    return `${labelPart}(${newRelative})`;
  };

  return rewriteOutsideCode(body, (segment) =>
    segment
      .replace(MARKDOWN_MD_LINK_RE, convertMarkdownLink)
      .replace(EMBED_RE, (_m, raw) => convertTarget(raw, { isEmbed: true }))
      .replace(WIKILINK_RE, (_m, raw) => convertTarget(raw, { isEmbed: false })),
  );
}

