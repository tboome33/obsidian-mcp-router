/**
 * Write a file so a reader never sees it half-written.
 *
 * `fs.writeFileSync` truncates the target and then streams into it. A crash, a
 * full disk, or a `kill -9` between those two moments leaves a real file at the
 * real path containing a prefix of the new content — and every one of this
 * repo's derived artefacts is JSON or markdown that a prefix corrupts:
 *
 *   - a truncated `wiki-meta/search-index.json` fails to parse, and the
 *     automatic repair path treats an unparseable file as "not ours" and
 *     PRESERVES it. The corruption would be sticky: nothing would ever rebuild
 *     over it, and every `search_smart` fallback would refuse, forever, until
 *     somebody deleted the file by hand.
 *   - a truncated `wiki/index.md` loses its `> Generated by …` marker along with
 *     the rest of the tail, which turns a generated file into what every
 *     consumer reads as a HAND-WRITTEN one — permanently protected from
 *     regeneration by the very conflict rule that protects real user content.
 *
 * In both cases an interrupted write does not degrade the artefact, it removes
 * the system's ability to fix it. Hence: write a sibling temp file, then rename
 * over the target. `rename` within one directory is atomic on POSIX and, via
 * `MoveFileEx(MOVEFILE_REPLACE_EXISTING)`, on Windows — a reader sees the whole
 * old file or the whole new one.
 *
 * The temp file is a SIBLING, not in the OS temp dir: `rename` is only atomic
 * within a filesystem, and a vault on another volume would silently degrade to
 * a copy. On any failure the temp file is removed, so a failed write leaves the
 * directory as it was rather than littering it with orphans.
 *
 * Scope: the on-disk writers (`okf-projections-fs`, `bm25-index-fs`). Writes
 * that go through the Local REST API are the plugin's business, not ours.
 */

import fs from 'node:fs';
import path from 'node:path';

/**
 * @param {string} absPath Target file (its directory must already exist).
 * @param {string} content
 * @param {object} [opts]
 * @param {object} [opts.fsMod] injected for tests
 */
export function writeFileAtomicSync(absPath, content, { fsMod = fs } = {}) {
  const dir = path.dirname(absPath);
  // Distinctive, per-call, in the same directory. `process.pid` + a counter
  // keeps two writers in one process (and two processes) off each other's temp
  // names; the rename itself is what makes the outcome safe either way.
  const tmp = path.join(dir, `.${path.basename(absPath)}.${process.pid}.${nextSeq()}.tmp`);
  try {
    fsMod.writeFileSync(tmp, content, 'utf8');
    fsMod.renameSync(tmp, absPath);
  } catch (err) {
    try { fsMod.unlinkSync(tmp); } catch { /* the temp file never existed, or is already gone */ }
    throw err;
  }
}

let seq = 0;
function nextSeq() {
  seq = (seq + 1) % 1_000_000;
  return seq;
}
