#!/usr/bin/env node
/**
 * build-mod-locales.mjs — writes `hooks/vault-panel/locale-fr.ts` from
 * `locales/fr.json`.
 *
 * The vault panel's texts live in `locales/<code>.json`, one file per
 * language, read at run time from the plugin's folder. A hooks module cannot
 * import a .json file, and Claude Code's test kit reads no file of the
 * plugin, so the French text is ALSO compiled into the module: it is what the
 * panel shows before (or without) reading the files, and what its tests see.
 * `tests/mod-locales.test.mjs` fails when the two drift — run this script
 * after editing fr.json.
 *
 * Usage: node scripts/build-mod-locales.mjs [--check]
 *   --check  exit 1 if the .ts file is not what this script would write.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'locales', 'fr.json');
const target = path.join(root, 'hooks', 'vault-panel', 'locale-fr.ts');

export function renderLocaleModule(json) {
  const body = JSON.stringify(json, null, 2);

  return (
    '// Generated by scripts/build-mod-locales.mjs from locales/fr.json — do not edit.\n'
    + '// The French texts, compiled in: what the panel shows before it reads\n'
    + '// locales/<code>.json, and what its tests see.\n'
    + `export const FR: Record<string, string> = ${body}\n`
  );
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const json = JSON.parse(fs.readFileSync(source, 'utf8'));
  const text = renderLocaleModule(json);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== text) {
      console.error('hooks/vault-panel/locale-fr.ts is stale: run `node scripts/build-mod-locales.mjs`.');
      process.exit(1);
    }
    console.log('locale-fr.ts is up to date.');
  } else {
    fs.writeFileSync(target, text);
    console.log(`wrote ${path.relative(root, target)}`);
  }
}
